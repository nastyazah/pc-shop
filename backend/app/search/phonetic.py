"""Груба звукова форма слова для української/російської: ловить помилки "на слух".
аператива = оператива, процессор = процесор, кулір = кулер, видеокарта = відеокарта.
Використовується лише як додатковий (нечіткий) збіг, тому зайві збіги коштують дешево."""
import re

_VOWELS = str.maketrans({"о": "а", "ё": "а", "е": "и", "є": "и", "я": "и", "ы": "и", "э": "и", "і": "и", "ї": "и", "ю": "у"})
_DEVOICE = str.maketrans({"б": "п", "д": "т", "г": "к", "ґ": "к", "з": "с", "в": "ф", "ж": "ш"})


def phonetic_key(word: str) -> str:
    w = word.lower()
    for ch in "'ʼ’ьъ":
        w = w.replace(ch, "")
    w = w.translate(_VOWELS)
    if w:
        w = w[:-1] + w[-1].translate(_DEVOICE)  # оглушення кінцевого приголосного
    return re.sub(r"(.)\1+", r"\1", w)  # подвоєні літери: процессор = процесор
